/* ---------------------------------------------------------
 * Read ADC1 electrical measurements
 *
 * ADC1 sequence:
 *
 * Rank 1 → ADC1_IN3 → I_ADC_SIDE12
 * Rank 2 → ADC1_IN5 → DUT_ADC
 * Rank 3 → ADC1_IN6 → I_ADC_SIDE21
 * Rank 4 → ADC1_IN7 → I_ADC_SIDE11
 * Rank 5 → ADC1_IN8 → I_ADC_SIDE22
 * --------------------------------------------------------- */
static void Inputs_ReadADC1(void)
{
    if (adc1_handle == NULL)
    {
        return;
    }


    /* Start one complete ADC1 regular sequence */
    if (HAL_ADC_REG_StartConv(adc1_handle) != HAL_OK)
    {
        return;
    }


    /* Rank 1 */
    if (HAL_ADC_REG_PollForConv(adc1_handle, 10) == HAL_OK)
    {
        inputs.i_adc_side12_raw =
            (uint16_t)HAL_ADC_REG_ReadConversionData(adc1_handle);
    }


    /* Rank 2 */
    if (HAL_ADC_REG_PollForConv(adc1_handle, 10) == HAL_OK)
    {
        inputs.dut_adc_raw =
            (uint16_t)HAL_ADC_REG_ReadConversionData(adc1_handle);
    }


    /* Rank 3 */
    if (HAL_ADC_REG_PollForConv(adc1_handle, 10) == HAL_OK)
    {
        inputs.i_adc_side21_raw =
            (uint16_t)HAL_ADC_REG_ReadConversionData(adc1_handle);
    }


    /* Rank 4 */
    if (HAL_ADC_REG_PollForConv(adc1_handle, 10) == HAL_OK)
    {
        inputs.i_adc_side11_raw =
            (uint16_t)HAL_ADC_REG_ReadConversionData(adc1_handle);
    }


    /* Rank 5 */
    if (HAL_ADC_REG_PollForConv(adc1_handle, 10) == HAL_OK)
    {
        inputs.i_adc_side22_raw =
            (uint16_t)HAL_ADC_REG_ReadConversionData(adc1_handle);
    }


    HAL_ADC_REG_StopConv(adc1_handle);


    inputs.current_side12_a =
    Inputs_ConvertCurrent(inputs.i_adc_side12_raw,
                          CURRENT_SIDE12_OFFSET_V,
                          CURRENT_SIDE12_SCALE);

    inputs.current_side21_a =
        Inputs_ConvertCurrent(inputs.i_adc_side21_raw,
                            CURRENT_SIDE21_OFFSET_V,
                            CURRENT_SIDE21_SCALE);

    inputs.current_side11_a =
        Inputs_ConvertCurrent(inputs.i_adc_side11_raw,
                            CURRENT_SIDE11_OFFSET_V,
                            CURRENT_SIDE11_SCALE);

    inputs.current_side22_a =
        Inputs_ConvertCurrent(inputs.i_adc_side22_raw,
                            CURRENT_SIDE22_OFFSET_V,
                            CURRENT_SIDE22_SCALE);

    inputs.dut_voltage_v =
        Inputs_ConvertDUTVoltage(inputs.dut_adc_raw,
                            DUT_VOLTAGE_OFFSET_V,
                            DUT_VOLTAGE_SCALE);

    inputs.total_current_a =
        inputs.current_side11_a +
        inputs.current_side12_a +
        inputs.current_side21_a +
        inputs.current_side22_a;

    inputs.power_w =
        inputs.dut_voltage_v * inputs.total_current_a;
    
}

static float Inputs_ConvertCurrent(uint16_t raw_adc, float offset_v, float scale)
{
    float adc_voltage;
    float current_a;

    /*
     * Convert ADC count to ADC pin voltage.
     */
    adc_voltage =
        ((float)raw_adc / ADC_MAX_COUNT) * ADC_VREF_V;


    /*
     * Remove measured zero-current voltage offset.
     */
    adc_voltage -= offset_v;


    /*
     * Convert voltage to stage current and apply
     * calibration scale factor.
     */
    current_a =
        adc_voltage * CURRENT_A_PER_V * scale;


    return current_a;
}

static float Inputs_ConvertDUTVoltage(uint16_t raw_adc,
                                      float offset_v,
                                      float scale)
{
    float adc_voltage;
    float dut_voltage;

    /* Convert ADC count to ADC pin voltage */
    adc_voltage =
        ((float)raw_adc / ADC_MAX_COUNT) * ADC_VREF_V;

    /* Remove ADC-side voltage offset */
    adc_voltage -= offset_v;

    /* Reverse the 15:1 sensing ratio (60:1 divider, x4 amplifier)
       and apply calibration scale */
    dut_voltage =
        adc_voltage * DUT_VOLTAGE_DIVIDER_RATIO * scale;

    return dut_voltage;
}




static bool Inputs_ConvertThermistor(uint16_t raw_adc,
                                     float beta_k,
                                     float *temperature_c)
{
    float voltage;
    float resistance;
    float inverse_kelvin;
    float result;

    /* Reject invalid ADC readings */
    if (temperature_c == NULL ||
        raw_adc == 0u ||
        raw_adc >= 4095u)
    {
        return false;
    }

    /* Convert ADC count to ADC pin voltage */
    voltage =
        ((float)raw_adc / ADC_MAX_COUNT) * ADC_VREF_V;

    if (voltage <= 0.0f ||
        voltage >= THERMISTOR_SUPPLY_V)
    {
        return false;
    }

    /*
     * High-side NTC:
     *
     * 2.5 V
     *   |
     *  NTC
     *   |
     *   +---- ADC
     *   |
     * 5.1k
     *   |
     *  GND
     */
    resistance =
        THERMISTOR_PULLDOWN_OHM *
        (THERMISTOR_SUPPLY_V / voltage - 1.0f);

    if (resistance <= 0.0f)
    {
        return false;
    }

    /* Beta equation */
    inverse_kelvin =
        (1.0f / THERMISTOR_T25_K) +
        logf(resistance / THERMISTOR_R25_OHM) / beta_k;

    if (inverse_kelvin <= 0.0f ||
        !isfinite(inverse_kelvin))
    {
        return false;
    }

    result = (1.0f / inverse_kelvin) - 273.15f;

    /* Reject unreasonable temperatures */
    if (!isfinite(result) ||
        result < -40.0f ||
        result > 150.0f)
    {
        return false;
    }

    *temperature_c = result;

    return true;
}



/* ---------------------------------------------------------
 * Read ADC2 thermistor channels
 *
 * ADC2 sequencer is arranged:
 *
 * Rank 1  → TH_ADC1
 * Rank 2  → TH_ADC2
 * ...
 * Rank 12 → TH_ADC12
 * --------------------------------------------------------- */
static void Inputs_ReadADC2(void)
{
    if (adc2_handle == NULL)
    {
        return;
    }


    /* Start one complete ADC2 regular sequence */
    if (HAL_ADC_REG_StartConv(adc2_handle) != HAL_OK)
    {
        return;
    }


    for (uint32_t i = 0; i < NUM_THERMISTORS; i++)
    {
        if (HAL_ADC_REG_PollForConv(adc2_handle, 10) == HAL_OK)
        {
            inputs.thermistor_raw[i] =
                (uint16_t)HAL_ADC_REG_ReadConversionData(adc2_handle);
        }
    }


    HAL_ADC_REG_StopConv(adc2_handle);


        /* Convert thermistor ADC readings to temperatures */
    for (uint32_t i = 0; i < NUM_THERMISTORS; i++)
    {
        float beta_k;

        /*
        * External DUT thermistors:
        *
        * Thermistor 4 -> index 3
        * Thermistor 5 -> index 4
        * Thermistor 6 -> index 5
        * Thermistor 7 -> index 6
        *
        * All other thermistors are internal.
        */
        if ((i >= 3U) && (i <= 6U))
        {
            beta_k = EXTERNAL_THERMISTOR_BETA_K;
        }
        else
        {
            beta_k = INTERNAL_THERMISTOR_BETA_K;
        }
        inputs.thermistor_valid[i] =
            Inputs_ConvertThermistor(
                inputs.thermistor_raw[i],
                beta_k,
                &inputs.thermistor_temp_c[i]);

        if (!inputs.thermistor_valid[i])
        {
            inputs.thermistor_temp_c[i] = NAN;
        }
    }

}




/* ---------------------------------------------------------
 * Return latest input values
 * --------------------------------------------------------- */
const Inputs_t *Inputs_Get(void)
{
    return &inputs;
}