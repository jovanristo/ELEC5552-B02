/* ---------------------------------------------------------
 * ADC / current-sense conversion constants
 * --------------------------------------------------------- */

#define ADC_MAX_COUNT               4095.0f
#define ADC_VREF_V                  2.5f
#define CURRENT_SENSE_MAX_V         2.25f
#define CURRENT_BRANCH_MAX_A         7.5f

#define CURRENT_A_PER_V \
    (CURRENT_BRANCH_MAX_A / CURRENT_SENSE_MAX_V)

//offset and scale values to change later 
/* SIDE12 */
#define CURRENT_SIDE12_OFFSET_V     0.0f
#define CURRENT_SIDE12_SCALE        1.0f

/* SIDE21 */
#define CURRENT_SIDE21_OFFSET_V     0.0f
#define CURRENT_SIDE21_SCALE        1.0f

/* SIDE11 */
#define CURRENT_SIDE11_OFFSET_V     0.0f
#define CURRENT_SIDE11_SCALE        1.0f

/* SIDE22 */
#define CURRENT_SIDE22_OFFSET_V     0.0f
#define CURRENT_SIDE22_SCALE        1.0f

/* ---------------------------------------------------------
 * ADC / DUT conversion constants
 * --------------------------------------------------------- */

#define DUT_VOLTAGE_DIVIDER_RATIO   15.0f   /* 60:1 divider x 4 amplifier gain */

#define DUT_VOLTAGE_OFFSET_V        0.0f
#define DUT_VOLTAGE_SCALE           1.0f


/* Latest processed input values */
static Inputs_t inputs;


/* ADC handles generated by CubeMX2 */
static hal_adc_handle_t *adc1_handle;
static hal_adc_handle_t *adc2_handle;


/* Private functions */
static void Inputs_ReadButtons(void);
static void Inputs_ReadADC1(void);
static float Inputs_ConvertCurrent(uint16_t raw_adc, float offset_v, float scale);
static float Inputs_ConvertDUTVoltage(uint16_t raw_adc, float offset_v, float scale);
static void Inputs_ReadADC2(void);
static bool Inputs_ConvertThermistor(uint16_t raw_adc, float beta_k, float *temperature_c);


/* ---------------------------------------------------------
 * Thermistor conversion constants
 * --------------------------------------------------------- */

// Thermistor 1  -> index 0  -> internal
// Thermistor 2  -> index 1  -> internal
// Thermistor 3  -> index 2  -> internal

// Thermistor 4  -> index 3  -> EXTERNAL
// Thermistor 5  -> index 4  -> EXTERNAL
// Thermistor 6  -> index 5  -> EXTERNAL
// Thermistor 7  -> index 6  -> EXTERNAL

// Thermistor 8  -> index 7  -> internal
// Thermistor 9  -> index 8  -> internal
// Thermistor 10 -> index 9  -> internal
// Thermistor 11 -> index 10 -> internal
// Thermistor 12 -> index 11 -> internal
 
#define THERMISTOR_SUPPLY_V      2.5f
#define THERMISTOR_PULLDOWN_OHM  5100.0f
#define THERMISTOR_R25_OHM       10000.0f
#define THERMISTOR_T25_K         298.15f

/* Thermistor-specific parameters */
#define INTERNAL_THERMISTOR_BETA_K   3950.0f  
#define EXTERNAL_THERMISTOR_BETA_K   3950.0f 



/* ---------------------------------------------------------
 * Initialise input processing
 * --------------------------------------------------------- */
void Inputs_Init(void)
{
    /* Get handles to CubeMX2-generated ADC peripherals */
    adc1_handle = mx_adc1_gethandle();
    adc2_handle = mx_adc2_gethandle();


    /*
     * Activate and calibrate ADC1.
     * CubeMX2 has already configured the ADC channels,
     * resolution, sequence, sampling times, etc.
     */
    if (adc1_handle != NULL)
    {
        HAL_ADC_Start(adc1_handle);
        HAL_ADC_Calibrate(adc1_handle);
    }


    /* Activate and calibrate ADC2 */
    if (adc2_handle != NULL)
    {
        HAL_ADC_Start(adc2_handle);
        HAL_ADC_Calibrate(adc2_handle);
    }
}


/* ---------------------------------------------------------
 * Update all MCU inputs
 * --------------------------------------------------------- */
void Inputs_Update(void)
{
    Inputs_ReadButtons();

    Inputs_ReadADC1();

    Inputs_ReadADC2();


    /*
     * USB VBUS input
     *
     * HIGH = USB VBUS present
     * LOW  = USB VBUS absent
     */
    inputs.usb_vbus_present =
        (HAL_GPIO_ReadPin(USB_VBUS_PORT,
                          USB_VBUS_PIN) == HAL_GPIO_PIN_SET);
}


